/** The parts of `tauri.conf.json` `init` writes once and leaves to the app; `sync` merges the owned parts over it. */
export function baseTauriConfig(manifest: Pick<DesktopManifest, 'devUrl'> & Partial<Pick<DesktopManifest, 'local'>>): JsonObject {
  let port = '3000'
  try {
    port = new URL(manifest.devUrl).port || port
  }
  catch {
    // The module validated it.
  }
  return {
    $schema: 'https://schema.tauri.app/config/2',
    build: {
      // Run in the app's directory (next to package.json).
      beforeDevCommand: `npx nuxt dev --port ${port}`,
      // Local mode: `frigear-desktop build` builds the server and the sidecar itself before \`tauri build\`.
      beforeBuildCommand: manifest.local ? '' : 'npx nuxt generate',
    },
    app: {
      security: { csp: null },
    },
    bundle: {
      targets: 'all',
      icon: ['icons/icon.png', 'icons/icon.ico'],
    },
  }
}

/**
 * Local mode: the page the window shows until the bundled server is ready (`build.frontendDist`). The Rust shell calls
 * `frigearServerFailed(message)` when the server exits before that.
 */
export function loadingPage(appName: string): string {
  const title = appName.replace(/[&<>"]/g, char => `&#${char.charCodeAt(0)};`)
  return `<!doctype html>
<!-- Generated by frigear-desktop sync (desktop.mode: 'local'). Do not edit: sync rewrites it. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>
  :root { color-scheme: light dark; font-family: system-ui, sans-serif; }
  body { margin: 0; height: 100vh; display: grid; place-items: center; background: Canvas; color: CanvasText; }
  .spinner { width: 28px; height: 28px; border: 3px solid color-mix(in srgb, CanvasText 20%, transparent); border-top-color: CanvasText; border-radius: 50%; animation: spin .8s linear infinite; margin: 0 auto 12px; }
  @keyframes spin { to { transform: rotate(360deg); } }
  main { text-align: center; max-width: 32rem; padding: 0 16px; }
  .error { display: none; }
  body.failed .spinner, body.failed .loading { display: none; }
  body.failed .error { display: block; }
</style>
</head>
<body>
<main>
  <div class="spinner"></div>
  <p class="loading">Starting ${title}…</p>
  <p class="error" id="error"></p>
</main>
<script>
  window.frigearServerFailed = function (message) {
    document.getElementById('error').textContent = message
    document.body.classList.add('failed')
  }
</script>
</body>
</html>
`
}

/** The library target of the crate: Rust identifiers have no `-`. */
export const libName = (crate: string): string => `${crate.replace(/-/g, '_')}_lib`

type Features = Pick<DesktopManifest, 'appId' | 'appName' | 'version' | 'singleInstance' | 'autostart' | 'updater'> & Partial<Pick<DesktopManifest, 'local'>>

export function cargoToml(manifest: Features): string {
  const crate = crateName(manifest.appId)
  const desktopDeps = [
    manifest.singleInstance ? 'tauri-plugin-single-instance = { version = "2", features = ["deep-link"] }' : null,
    manifest.autostart ? 'tauri-plugin-autostart = "2"' : null,
    manifest.updater ? 'tauri-plugin-updater = "2"' : null,
  ].filter(Boolean)
  return `[package]
name = "${crate}"
version = "${manifest.version}"
description = ${JSON.stringify(manifest.appName)}
edition = "2021"

[lib]
# The \`_lib\` suffix keeps the library apart from the binary of the same name (cargo#8519).
name = "${libName(crate)}"
crate-type = ["staticlib", "cdylib", "rlib"]

[build-dependencies]
tauri-build = { version = "2", features = [] }

[dependencies]
tauri = { version = "2", features = [] }
tauri-plugin-opener = "2"
tauri-plugin-deep-link = "2"
tauri-plugin-store = "2"
${manifest.local ? 'tauri-plugin-shell = "2"\n' : ''}serde = { version = "1", features = ["derive"] }
serde_json = "1"
${desktopDeps.length
  ? `
[target.'cfg(not(any(target_os = "android", target_os = "ios")))'.dependencies]
${desktopDeps.join('\n')}
`
  : ''}`
}

export function libRs(manifest: Features): string {
  const desktop: string[] = []
  if (manifest.singleInstance) {
    desktop.push(`        // First: a second launch, and every deep link on Windows and Linux, starts a second process. With the
        // \`deep-link\` feature this hands the URL to the deep-link plugin of the running app and quits.
        builder = builder.plugin(tauri_plugin_single_instance::init(|app, _argv, _cwd| {
            use tauri::Manager;
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }));`)
  }
  if (manifest.autostart) {
    desktop.push(`        builder = builder.plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            None,
        ));`)
  }
  if (manifest.updater) {
    desktop.push('        builder = builder.plugin(tauri_plugin_updater::Builder::new().build());')
  }
  const local = manifest.local
  return `// Generated by frigear-desktop init. Yours to change: \`frigear-desktop sync\` never touches this file.
${local ? localServerRs(local) : ''}
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    #[allow(unused_mut)]
    let mut builder = tauri::Builder::default();

    #[cfg(desktop)]
    {
${desktop.join('\n\n') || '        // Desktop-only plugins go here.'}
    }

    builder
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_deep_link::init())
        .plugin(tauri_plugin_store::Builder::new().build())${local ? '\n        .plugin(tauri_plugin_shell::init())' : ''}
        .setup(|_app| {
            // Linux, and Windows in development, register the deep-link schemes at runtime (macOS reads them from the
            // bundle, an installed Windows app from the installer).
            #[cfg(any(target_os = "linux", all(debug_assertions, windows)))]
            {
                use tauri_plugin_deep_link::DeepLinkExt;
                _app.deep_link().register_all()?;
            }${local
              ? `
            // The bundled server. Under \`tauri dev\` the window loads \`nuxt dev\` instead (devUrl).
            #[cfg(not(dev))]
            local_server::start(_app.handle())?;`
              : ''}
            Ok(())
        })${local
          ? `
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|_app, _event| {
            // Stop the bundled server with the app.
            #[cfg(not(dev))]
            if let tauri::RunEvent::Exit = _event {
                local_server::stop(_app);
            }
        });`
          : `
        .run(tauri::generate_context!())
        .expect("error while running tauri application");`}
}
`
}

/**
 * Local mode: starts the sidecar with the data folder and port, waits for its \`READY <port>\` line, then navigates the
 * main window (showing the loading page) to the server. A server that exits before it is ready is reported on the
 * loading page. The sidecar generates its own secrets into the data folder on the first start. It is killed on exit, and
 * stops by itself when the shell dies without exiting (its stdin closes, \`FRIGEAR_DESKTOP_PARENT_WATCH\`).
 */
function localServerRs(local: NonNullable<DesktopManifest['local']>): string {
  return `
/// The bundled server (\`desktop.mode: 'local'\`).
#[cfg(not(dev))]
mod local_server {
    use std::sync::Mutex;
    use tauri::{AppHandle, Manager};
    use tauri_plugin_shell::{process::{CommandChild, CommandEvent}, ShellExt};

    /// The sidecar's name (\`desktop.local.binaryName\`, \`bundle.externalBin\`).
    const SIDECAR: &str = ${JSON.stringify(local.binaryName)};
    /// The folder inside the app-data folder that holds the database and the secrets (\`desktop.local.dataDirName\`).
    const DATA_DIR_NAME: &str = ${JSON.stringify(local.dataDirName)};
    /// \`desktop.local.port\`; 0 lets the OS pick a free one.
    const PORT: u16 = ${local.port};

    struct Server(Mutex<Option<CommandChild>>);

    /// The port of the server's \`READY <port>\` line.
    pub fn parse_ready(line: &str) -> Option<u16> {
        line.trim().strip_prefix("READY ").and_then(|port| port.trim().parse().ok())
    }

    pub fn start(app: &AppHandle) -> Result<(), Box<dyn std::error::Error>> {
        let data_dir = app.path().app_data_dir()?.join(DATA_DIR_NAME);
        std::fs::create_dir_all(&data_dir)?;
        let (mut events, child) = app
            .shell()
            .sidecar(SIDECAR)?
            .env("PORT", PORT.to_string())
            .env("HOST", "127.0.0.1")
            .env("DATA_DIR", &data_dir)
            // The server stops by itself when its stdin closes. The child below holds the pipe's write end until
            // \`stop\`, and the OS closes it when this process dies however it dies (a crash, \`kill -9\`), so the server
            // never outlives the app.
            .env("FRIGEAR_DESKTOP_PARENT_WATCH", "1")
            .current_dir(&data_dir)
            .spawn()?;
        app.manage(Server(Mutex::new(Some(child))));

        let app = app.clone();
        tauri::async_runtime::spawn(async move {
            let mut ready = false;
            while let Some(event) = events.recv().await {
                match event {
                    CommandEvent::Stdout(bytes) => {
                        let line = String::from_utf8_lossy(&bytes);
                        if !ready {
                            if let Some(port) = parse_ready(&line) {
                                ready = true;
                                if let (Some(window), Ok(url)) = (
                                    app.get_webview_window("main"),
                                    format!("http://127.0.0.1:{port}/").parse::<tauri::Url>(),
                                ) {
                                    let _ = window.navigate(url);
                                }
                                continue;
                            }
                        }
                        println!("{line}");
                    }
                    CommandEvent::Stderr(bytes) => eprintln!("{}", String::from_utf8_lossy(&bytes)),
                    CommandEvent::Error(message) => eprintln!("[desktop] server: {message}"),
                    CommandEvent::Terminated(status) => {
                        if !ready {
                            let message = format!("The app's server stopped before it was ready (exit code {:?}).", status.code);
                            if let Some(window) = app.get_webview_window("main") {
                                let message = serde_json::to_string(&message).unwrap_or_default();
                                let _ = window.eval(&format!("window.frigearServerFailed && window.frigearServerFailed({message})"));
                            }
                        }
                        break;
                    }
                    _ => {}
                }
            }
        });
        Ok(())
    }

    pub fn stop(app: &AppHandle) {
        if let Some(server) = app.try_state::<Server>() {
            if let Some(child) = server.0.lock().ok().and_then(|mut child| child.take()) {
                let _ = child.kill();
            }
        }
    }
}
`
}


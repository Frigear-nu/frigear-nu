import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { TAURI_PLUGINS, type TauriPluginName } from './runtime/shared/native'

// Build-time helpers of the module, pure so they can be tested without a Nuxt build.

/** The source of `#desktop/native`: a lazy loader per installed Tauri package, `null` for the others. */
export function nativeLoaderTemplate(installed: Record<TauriPluginName, boolean>): string {
  const entries = (Object.keys(TAURI_PLUGINS) as TauriPluginName[]).map((key) => {
    return `  ${key}: ${installed[key] ? `() => import(${JSON.stringify(TAURI_PLUGINS[key].specifier)})` : 'null'},`
  })
  return [
    '// Generated by @frigear-nu/desktop: only installed Tauri packages are imported, so a missing optional peer never',
    '// fails the build.',
    `export const plugins = {\n${entries.join('\n')}\n}`,
    '',
  ].join('\n')
}

/** Whether `pkg` is installed for an app in `rootDir` (its `node_modules`, a parent's, or one of `modulesDirs`). */
export function isPackageInstalled(pkg: string, rootDir: string, modulesDirs: string[] = []): boolean {
  const dirs = new Set(modulesDirs)
  for (let dir = rootDir; ; dir = dirname(dir)) {
    dirs.add(join(dir, 'node_modules'))
    if (dirname(dir) === dir) break
  }
  return [...dirs].some(dir => existsSync(join(dir, pkg, 'package.json')))
}

/**
 * A desktop app in remote mode cannot carry a same-origin session cookie to the API: Auth has to run as an OAuth
 * client. Throws for any other mode.
 */
export function assertClientAuth(mode: string): void {
  if (mode !== 'client') {
    throw new Error('[@frigear-nu/desktop] `@frigear-nu/auth` runs in server mode, which needs a same-origin session cookie a Tauri app in remote mode cannot send: set `authentication.mode: \'client\'` in the app\'s config.')
  }
}

/** Warnings about Tauri packages the enabled features need but the app has not installed. */
export function missingPluginWarnings(plugins: { name: string, required: boolean, feature: string }[], installed: (pkg: string) => boolean): string[] {
  return plugins
    .filter(plugin => !installed(plugin.name))
    .map(plugin => `\`${plugin.name}\` is not installed (${plugin.feature})${plugin.required ? '' : ', optional'}: \`pnpm add ${plugin.name}\`.`)
}

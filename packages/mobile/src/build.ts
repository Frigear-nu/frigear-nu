import { existsSync } from 'node:fs'
import type { NetworkInterfaceInfo } from 'node:os'
import { dirname, join } from 'node:path'
import type { MobileTab } from './types'
import { NATIVE_PLUGINS, type NativePluginName } from './runtime/shared/native'

// Build-time helpers of the module, pure so they can be tested without a Nuxt build.

/** The source of `#mobile/native`: a lazy loader per installed native plugin, `null` for the others. */
export function nativeLoaderTemplate(installed: Record<NativePluginName, boolean>): string {
  const entries = (Object.keys(NATIVE_PLUGINS) as NativePluginName[]).map((key) => {
    const { pkg, name } = NATIVE_PLUGINS[key]
    return `  ${key}: ${installed[key] ? `() => import(${JSON.stringify(pkg)}).then(m => m.${name})` : 'null'},`
  })
  return [
    '// Generated by @frigear-nu/mobile: only installed native plugins are imported, so a missing optional peer never',
    '// fails the build.',
    `export const plugins = {\n${entries.join('\n')}\n}`,
    '',
  ].join('\n')
}

/** The source of `#mobile/tabs`. */
export function tabsTemplate(tabs: MobileTab[]): string {
  return `export const tabs = ${JSON.stringify(tabs, null, 2)}\n`
}

/** The first private IPv4 address of this machine (what a phone on the same Wi-Fi reaches it at). */
export function pickLanAddress(interfaces: NodeJS.Dict<NetworkInterfaceInfo[]>): string | undefined {
  const candidates = Object.entries(interfaces)
    .flatMap(([name, list]) => (list ?? []).map(info => ({ name, info })))
    .filter(({ info }) => info.family === 'IPv4' && !info.internal)
    .map(({ name, info }) => ({ name, address: info.address }))
  const isPrivate = (address: string) => /^(?:10\.|192\.168\.|172\.(?:1[6-9]|2\d|3[01])\.)/.test(address)
  // Wi-Fi / Ethernet (en*, eth*, wlan*) before VPN and bridge interfaces.
  const rank = (name: string) => (/^(?:en|eth|wlan|wl)/.test(name) ? 0 : 1)
  return candidates
    .filter(candidate => isPrivate(candidate.address))
    .sort((a, b) => rank(a.name) - rank(b.name))[0]?.address
}

/**
 * The LAN host of a `MOBILE_LAN` build, or `undefined`. `nuxt dev` never needs it (the live-reload URL already points
 * at the machine), and a release build (`MOBILE_RELEASE=1`) refuses it so a LAN address never ships.
 */
export function resolveLanHost(input: {
  dev: boolean
  option: boolean | string | undefined
  env: Record<string, string | undefined>
  interfaces: () => NodeJS.Dict<NetworkInterfaceInfo[]>
}): string | undefined {
  const flag = input.env.MOBILE_LAN?.trim()
  if (!flag || flag === '0' || flag === 'false' || input.dev || input.option === false) return undefined
  if (input.env.MOBILE_RELEASE === '1' || input.env.MOBILE_RELEASE === 'true') {
    throw new Error('[@frigear-nu/mobile] MOBILE_LAN and MOBILE_RELEASE are both set: a release build must not point at a development machine.')
  }
  if (flag !== '1' && flag !== 'true') return flag
  if (typeof input.option === 'string' && input.option) return input.option
  const address = pickLanAddress(input.interfaces())
  if (!address) throw new Error('[@frigear-nu/mobile] MOBILE_LAN is set but no LAN address was found. Set `MOBILE_LAN=<address>`.')
  return address
}

/** Lowercase URL schemes the native projects register: the OAuth redirect URI's and the deep-link schemes. */
export function resolveSchemes(redirectUri: string | undefined, deepLinkSchemes: string[]): string[] {
  const schemes = new Set<string>()
  const redirectScheme = redirectUri && /^([a-z][a-z0-9+.-]*):/i.exec(redirectUri)?.[1]?.toLowerCase()
  if (redirectScheme && redirectScheme !== 'https' && redirectScheme !== 'http') schemes.add(redirectScheme)
  for (const scheme of deepLinkSchemes) schemes.add(scheme.toLowerCase())
  return [...schemes]
}

/** The native plugins the enabled features use. */
export function usedPlugins(input: {
  nativeChrome: boolean
  statusBar: boolean
  keyboardAccessoryBar: boolean
  oauth: boolean
}): { name: string, required: boolean, feature: string }[] {
  const keys: NativePluginName[] = ['app', 'haptics', 'actionSheet', 'dialog', 'share']
  if (input.statusBar) keys.push('statusBar')
  if (input.keyboardAccessoryBar) keys.push('keyboard')
  if (input.nativeChrome) keys.push('nativeNavigation')
  const plugins = [
    { name: '@capacitor/core', required: true, feature: 'Capacitor' },
    ...keys.map(key => ({ name: NATIVE_PLUGINS[key].pkg, required: !!NATIVE_PLUGINS[key].required, feature: NATIVE_PLUGINS[key].feature })),
  ]
  if (input.oauth) {
    plugins.push(
      { name: '@capacitor/browser', required: true, feature: 'sign-in (@frigear-nu/oauth-client)' },
      { name: '@aparajita/capacitor-secure-storage', required: false, feature: 'Keychain token storage (@frigear-nu/oauth-client)' },
    )
  }
  return plugins
}

/** Whether `pkg` is installed for an app in `rootDir` (its `node_modules`, a parent's, or one of `modulesDirs`). */
export function isPackageInstalled(pkg: string, rootDir: string, modulesDirs: string[] = []): boolean {
  const dirs = new Set(modulesDirs)
  for (let dir = rootDir; ; dir = dirname(dir)) {
    dirs.add(join(dir, 'node_modules'))
    if (dirname(dir) === dir) break
  }
  return [...dirs].some(dir => existsSync(join(dir, pkg, 'package.json')))
}

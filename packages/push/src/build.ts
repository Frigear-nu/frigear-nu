import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { ModuleDependencyMeta } from '@nuxt/schema'
import { resolveAuthMode } from '@frigear-nu/auth/mode'

// Build-time helpers of the module, pure so they can be tested without a Nuxt build.

/** The file notify's `#notify/push-driver` points at when push is installed (see `runtime/server/notify-driver.ts`). */
export const PUSH_NOTIFY_DRIVER = fileURLToPath(new URL('./runtime/server/notify-driver', import.meta.url))

/**
 * The modules Nuxt installs for push, by the app's `authentication.mode`. Server mode owns the tables, routes and the
 * admin tab, so it needs the database, users and notify. Client mode (the mobile app) is only the device side: it must not
 * pull any of those into an app that has no server.
 */
export function pushModuleDependencies(nuxt: { options: object }): Record<string, ModuleDependencyMeta> {
  if (resolveAuthMode(nuxt) === 'client') {
    return {
      '@frigear-nu/module-kit': { version: '>=0.0.1' },
      '@frigear-nu/auth': { version: '>=0.0.1' },
      '@frigear-nu/mobile': { version: '>=0.0.0', optional: true },
    }
  }
  return {
    '@nuxthub/core': { version: '>=0.10' },
    '@frigear-nu/module-kit': { version: '>=0.0.1' },
    '@frigear-nu/auth': { version: '>=0.0.1' },
    '@frigear-nu/users': { version: '>=0.0.1' },
    // Push is notify's push driver: a `dispatchPushNotification` (and the push channel of notify's `notifyUser`) reaches
    // the stored devices. A `notify.push.driver` the app sets wins.
    '@frigear-nu/notify': { version: '>=0.0.1', defaults: { push: { driver: PUSH_NOTIFY_DRIVER } } },
    // The admin tab is built from its components (`TableCard`, ...).
    '@frigear-nu/ui': { version: '>=0.0.1' },
    '@frigear-nu/widget': { version: '>=0.0.0', optional: true },
    // The admin user tab lives on its admin user page, so it is only added with it.
    '@frigear-nu/admin': { version: '>=0.0.0', optional: true },
    // The account devices page is listed in the account menu.
    '@frigear-nu/menu': { version: '>=0.0.1', optional: true },
    '@frigear-nu/account': { version: '>=0.0.0', optional: true },
    '@frigear-nu/mobile': { version: '>=0.0.0', optional: true },
  }
}

/** Whether `pkg` can be resolved from the app (its root, a parent, or one of the Nuxt module directories). */
export function isPackageInstalled(pkg: string, rootDir: string, modulesDirs: string[] = []): boolean {
  const dirs = new Set(modulesDirs)
  for (let dir = rootDir; ; dir = dirname(dir)) {
    dirs.add(join(dir, 'node_modules'))
    if (dirname(dir) === dir) break
  }
  return [...dirs].some(dir => existsSync(join(dir, pkg, 'package.json')))
}

/**
 * The push plugin the app registers with: `firebase` (`@capacitor-firebase/messaging`, the FCM token on iOS and
 * Android), `capacitor` (`@capacitor/push-notifications`, the APNs token on iOS) or `null` when neither is installed.
 * Firebase wins when both are: its own docs say not to install another push plugin next to it.
 */
export type NativePushPlugin = 'firebase' | 'capacitor' | null

export function detectNativePushPlugin(isInstalled: (pkg: string) => boolean): NativePushPlugin {
  if (!isInstalled('@capacitor/core')) return null
  if (isInstalled('@capacitor-firebase/messaging')) return 'firebase'
  if (isInstalled('@capacitor/push-notifications')) return 'capacitor'
  return null
}

/**
 * The source of `#push/native`: a lazy loader of the push plugin, the platform and the provider of its token, or `null`
 * when no plugin is installed, so a missing optional peer never fails the build. `helper` exports `withoutThen` (a
 * loader cannot resolve to the bare plugin proxy), `fromFirebaseMessaging` and `capacitorPushProvider` (see
 * `runtime/app/utils/native.ts`).
 */
export function nativeLoaderTemplate(plugin: NativePushPlugin, helper: string): string {
  const loader = {
    firebase: 'export const loadPushNotifications = () => Promise.all([import("@capacitor-firebase/messaging"), import("@capacitor/core")]).then(([messaging, core]) => ({ plugin: fromFirebaseMessaging(messaging.FirebaseMessaging), platform: core.Capacitor.getPlatform(), provider: "fcm" }))',
    capacitor: 'export const loadPushNotifications = () => Promise.all([import("@capacitor/push-notifications"), import("@capacitor/core")]).then(([push, core]) => ({ plugin: withoutThen(push.PushNotifications), platform: core.Capacitor.getPlatform(), provider: capacitorPushProvider(core.Capacitor.getPlatform()) }))',
  }
  return [
    '// Generated by @frigear-nu/push: the push plugin is only imported when it is installed.',
    `import { capacitorPushProvider, fromFirebaseMessaging, withoutThen } from ${JSON.stringify(helper)}`,
    plugin ? loader[plugin] : 'export const loadPushNotifications = null',
    '',
  ].join('\n')
}

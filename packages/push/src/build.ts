import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import type { ModuleDependencyMeta } from '@nuxt/schema'
import { resolveAuthMode } from '@frigear-nu/auth/mode'
import type { NotificationTopic } from './types'

// Build-time helpers of the module, pure so they can be tested without a Nuxt build.

/**
 * The modules Nuxt installs for push, by the app's `authentication.mode`. Server mode owns the tables, routes and
 * pages, so it needs the database, users and notify. Client mode (the mobile app) is only the device side: it must not
 * pull any of those into an app that has no server.
 */
export function pushModuleDependencies(nuxt: { options: object }): Record<string, ModuleDependencyMeta> {
  if (resolveAuthMode(nuxt) === 'client') {
    return {
      '@frigear-nu/module-kit': { version: '>=0.0.1' },
      '@frigear-nu/auth': { version: '>=0.0.1' },
      '@frigear-nu/mobile': { version: '>=0.0.0', optional: true },
    }
  }
  return {
    '@nuxthub/core': { version: '>=0.10' },
    '@frigear-nu/module-kit': { version: '>=0.0.1' },
    '@frigear-nu/auth': { version: '>=0.0.1' },
    '@frigear-nu/users': { version: '>=0.0.1' },
    // `notifyUser` sends email and SMS through its dispatchers.
    '@frigear-nu/notify': { version: '>=0.0.1' },
    // The account page and the admin tab are built from its components (`TableCard`, `PageHeading`, ...).
    '@frigear-nu/ui': { version: '>=0.0.1' },
    '@frigear-nu/menu': { version: '>=0.0.1', optional: true },
    '@frigear-nu/account': { version: '>=0.0.0', optional: true },
    '@frigear-nu/widget': { version: '>=0.0.0', optional: true },
    // The admin user tab lives on its admin user page, so it is only added with it.
    '@frigear-nu/admin': { version: '>=0.0.0', optional: true },
    '@frigear-nu/mobile': { version: '>=0.0.0', optional: true },
  }
}

/** Whether `pkg` can be resolved from the app (its root, a parent, or one of the Nuxt module directories). */
export function isPackageInstalled(pkg: string, rootDir: string, modulesDirs: string[] = []): boolean {
  const dirs = new Set(modulesDirs)
  for (let dir = rootDir; ; dir = dirname(dir)) {
    dirs.add(join(dir, 'node_modules'))
    if (dirname(dir) === dir) break
  }
  return [...dirs].some(dir => existsSync(join(dir, pkg, 'package.json')))
}

/**
 * The source of `#push/native`: a lazy loader of the Capacitor push plugin and the platform, or `null` when the
 * plugin is not installed, so a missing optional peer never fails the build. `helper` exports `withoutThen`: a loader
 * cannot resolve to the bare plugin proxy (see `runtime/app/utils/native.ts`).
 */
export function nativeLoaderTemplate(installed: boolean, helper: string): string {
  return [
    '// Generated by @frigear-nu/push: the Capacitor plugin is only imported when it is installed.',
    `import { withoutThen } from ${JSON.stringify(helper)}`,
    installed
      ? 'export const loadPushNotifications = () => Promise.all([import("@capacitor/push-notifications"), import("@capacitor/core")]).then(([push, core]) => ({ plugin: withoutThen(push.PushNotifications), platform: core.Capacitor.getPlatform() }))'
      : 'export const loadPushNotifications = null',
    '',
  ].join('\n')
}

/** The source of the server-side `#push/topics`. */
export function topicsTemplate(topics: NotificationTopic[]): string {
  return `export const topics = ${JSON.stringify(topics, null, 2)}\n`
}
